"""Hand-authored money primitives tests (REQ-MONEY-001..006, REQ-INV-005).

Every expected value here is computed by hand, not generated by the code under
test, so these vectors are usable as an independent reference (12.4).
"""

from __future__ import annotations

import unittest
from decimal import Decimal

from contracts.errors import ConfigError, MoneyError
from core.money import (
    allocate_minor,
    add_minor,
    convert_minor,
    exponent_of,
    from_minor,
    parse_decimal,
    parse_rate,
    scale_minor,
    sub_minor,
    to_minor,
)


class ExponentRegistryTests(unittest.TestCase):
    def test_known_exponents(self) -> None:
        self.assertEqual(exponent_of("KZT"), 2)
        self.assertEqual(exponent_of("USD"), 2)
        self.assertEqual(exponent_of("JPY"), 0)
        self.assertEqual(exponent_of("KWD"), 3)

    def test_unknown_currency_is_rejected(self) -> None:
        with self.assertRaises(MoneyError):
            exponent_of("ZZZ")

    def test_non_string_currency_is_rejected(self) -> None:
        with self.assertRaises(MoneyError):
            exponent_of(643)  # type: ignore[arg-type]


class DecimalParsingTests(unittest.TestCase):
    def test_decimal_from_string(self) -> None:
        self.assertEqual(parse_decimal("0.5125"), Decimal("0.5125"))

    def test_float_is_forbidden(self) -> None:
        with self.assertRaises(MoneyError):
            parse_decimal(0.5)  # type: ignore[arg-type]

    def test_bool_is_forbidden(self) -> None:
        with self.assertRaises(MoneyError):
            parse_decimal(True)  # type: ignore[arg-type]

    def test_nan_and_infinity_rejected(self) -> None:
        for bad in ("NaN", "Infinity", "-Infinity"):
            with self.subTest(value=bad), self.assertRaises(MoneyError):
                parse_decimal(bad)

    def test_empty_and_garbage_rejected(self) -> None:
        for bad in ("", "   ", "abc", "1,5"):
            with self.subTest(value=bad), self.assertRaises(MoneyError):
                parse_decimal(bad)

    def test_rate_must_be_positive(self) -> None:
        with self.assertRaises(MoneyError):
            parse_rate("0")
        with self.assertRaises(MoneyError):
            parse_rate("-1.5")


class MinorUnitTests(unittest.TestCase):
    def test_to_minor_two_decimals(self) -> None:
        result = to_minor("1234.56", "KZT")
        self.assertEqual(result.amount_minor, 123456)
        self.assertEqual(result.rounding_operations, 0)

    def test_to_minor_zero_decimals(self) -> None:
        self.assertEqual(to_minor("1200", "JPY").amount_minor, 1200)

    def test_to_minor_three_decimals(self) -> None:
        self.assertEqual(to_minor("12.345", "KWD").amount_minor, 12345)

    def test_half_even_boundary(self) -> None:
        # 2.345 * 100 = 234.5 -> half-even rounds to 234 (4 is even)
        self.assertEqual(to_minor("2.345", "KZT", mode="ROUND_HALF_EVEN").amount_minor, 234)
        # 2.355 * 100 = 235.5 -> half-even rounds to 236 (6 is even)
        self.assertEqual(to_minor("2.355", "KZT", mode="ROUND_HALF_EVEN").amount_minor, 236)

    def test_half_up_boundary(self) -> None:
        self.assertEqual(to_minor("2.345", "KZT", mode="ROUND_HALF_UP").amount_minor, 235)

    def test_round_down_and_up(self) -> None:
        self.assertEqual(to_minor("2.349", "KZT", mode="ROUND_DOWN").amount_minor, 234)
        self.assertEqual(to_minor("2.341", "KZT", mode="ROUND_UP").amount_minor, 235)

    def test_rounding_trace_records_operation(self) -> None:
        result = to_minor("2.345", "KZT", mode="ROUND_HALF_EVEN")
        self.assertEqual(result.rounding_operations, 1)
        self.assertEqual(result.trace.mode, "ROUND_HALF_EVEN")

    def test_unknown_rounding_mode(self) -> None:
        with self.assertRaises(ConfigError):
            to_minor("1.00", "KZT", mode="ROUND_BANKERS")

    def test_from_minor_is_exact(self) -> None:
        self.assertEqual(from_minor(123456, "KZT"), Decimal("1234.56"))
        self.assertEqual(from_minor(12345, "KWD"), Decimal("12.345"))

    def test_overflow_is_bounded(self) -> None:
        with self.assertRaises(MoneyError):
            to_minor("999999999999999999", "KZT")


class ConversionTests(unittest.TestCase):
    def test_usd_to_kzt(self) -> None:
        # 100.00 USD at 512.50 KZT/USD = 51,250.00 KZT
        result = convert_minor(10000, "USD", "KZT", "512.50")
        self.assertEqual(result.amount_minor, 5125000)
        self.assertEqual(result.rounding_operations, 0)

    def test_jpy_zero_exponent(self) -> None:
        # 150,000 JPY at 0.0034 KZT/JPY = 510.00 KZT = 51000 minor units
        result = convert_minor(150000, "JPY", "KZT", "0.0034")
        self.assertEqual(result.amount_minor, 51000)

    def test_kwd_three_exponent(self) -> None:
        # 1.234 KWD (1234 minor) at 3.0 KZT/KWD = 3.702 KZT = 370.2 minor -> 370
        result = convert_minor(1234, "KWD", "KZT", "3.0")
        self.assertEqual(result.amount_minor, 370)
        self.assertEqual(result.rounding_operations, 1)

    def test_same_currency_is_identity(self) -> None:
        self.assertEqual(convert_minor(98765, "KZT", "KZT", "1").amount_minor, 98765)

    def test_round_trip_within_one_minor_unit(self) -> None:
        rate = Decimal("512.35")
        inverse = (Decimal(1) / rate).quantize(Decimal("0.000000000001"))
        forward = convert_minor(123456, "USD", "KZT", rate).amount_minor
        backward = convert_minor(forward, "KZT", "USD", inverse).amount_minor
        self.assertLessEqual(abs(backward - 123456), 1)

    def test_zero_rate_rejected(self) -> None:
        with self.assertRaises(MoneyError):
            convert_minor(100, "USD", "KZT", "0")

    def test_float_amount_rejected(self) -> None:
        with self.assertRaises(MoneyError):
            convert_minor(100.0, "USD", "KZT", "1.0")  # type: ignore[arg-type]


class IntegerArithmeticTests(unittest.TestCase):
    def test_add_and_sub(self) -> None:
        self.assertEqual(add_minor(100, 250, 3), 353)
        self.assertEqual(sub_minor(1000, 250), 750)

    def test_scale_minor(self) -> None:
        # 3 units of 333.33 = 999.99 KZT
        self.assertEqual(scale_minor(33333, "3").amount_minor, 99999)

    def test_scale_minor_rounds_half_even(self) -> None:
        # 1.5 * 33333 = 49999.5 -> 50000 (half-even, 0 even)
        self.assertEqual(scale_minor(33333, "1.5").amount_minor, 50000)

    def test_allocation_preserves_total(self) -> None:
        parts = allocate_minor(1000, [1, 1, 1])
        self.assertEqual(sum(parts), 1000)
        self.assertEqual(sorted(parts), [333, 333, 334])

    def test_allocation_rejects_zero_weights(self) -> None:
        with self.assertRaises(MoneyError):
            allocate_minor(1000, [0, 0])

    def test_allocation_rejects_empty(self) -> None:
        with self.assertRaises(MoneyError):
            allocate_minor(1000, [])

    def test_allocation_negative_weight(self) -> None:
        with self.assertRaises(MoneyError):
            allocate_minor(1000, [5, -1])


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
