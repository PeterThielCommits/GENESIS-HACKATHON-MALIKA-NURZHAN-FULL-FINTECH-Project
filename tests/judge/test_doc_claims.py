class TestPublishedFactsAreStateIndependent(unittest.TestCase):
    """A published fact must not depend on which target ran most recently.

    `make verify-core` writes a six-gate summary over the twelve-gate one. Any
    documented number read from that file then describes the *last run* rather
    than the repository, so `make verify-core && make docs-verify` failed on a
    correct tree. This is D-15-01's rule, and the test count was the third
    occurrence, so the rule is now asserted directly rather than trusted.
    """

    def test_test_count_comes_from_discovery_not_the_summary(self):
        source = (REPO_ROOT / "tools" / "verify_doc_claims.py").read_text(encoding="utf-8")
        # The fact definition must not reach into verify_summary.json for a count.
        fact_block = source[source.index('"id": "F-TESTS"') : source.index('"id": "F-ARTIFACTS"')]
        self.assertNotIn("_count_from_check", fact_block)
        self.assertIn("_discovered_test_count", fact_block)

    def test_discovered_counts_match_the_native_runner(self):
        import unittest

        suite = unittest.TestLoader().discover(start_dir=str(REPO_ROOT / "tests"), top_level_dir=str(REPO_ROOT))
        self.assertEqual(vdc._discovered_test_count(), suite.countTestCases())

    def test_official_count_is_discovered_independently(self):
        import unittest

        suite = unittest.TestLoader().discover(
            start_dir=str(REPO_ROOT / "tests" / "official"), top_level_dir=str(REPO_ROOT)
        )
        self.assertEqual(vdc._discovered_test_count("tests/official"), suite.countTestCases())
        self.assertGreater(vdc._discovered_test_count("tests/official"), 0)

    @unittest.skipUnless(ARTIFACTS_READY, NOT_READY_REASON)
    def test_core_mode_evidence_is_detected(self):
        """The predicate itself: a core summary must be recognised as such.

        Guarded by ARTIFACTS_READY, not by an in-body ``skipTest``: inside RC-001
        no summary exists yet by construction, and an ungated read of it turned
        the whole gate red with ``FileNotFoundError`` on a clean tree. That is the
        bootstrap trap this module's docstring warns about, met one more time.
        """
        summary_path = vdc.REPORT_DIR / "verify_summary.json"
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        expected = summary.get("mode") != "core"
        self.assertEqual(_full_mode_evidence(), expected)


