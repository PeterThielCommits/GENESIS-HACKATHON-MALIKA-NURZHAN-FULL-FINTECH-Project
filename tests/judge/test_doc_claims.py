ARTIFACTS_READY = (
    (vdc.REPORT_DIR / "verify_summary.json").is_file()
    and (vdc.REPORT_DIR / "report_index.json").is_file()
    and (vdc.REPORT_DIR / "replay_report.json").is_file()
    and vdc.TRAJECTORY_LOG.is_file()
)
def _full_mode_evidence() -> bool:
    """True when the evidence dir holds a *full* Judge Kit run.

    ``verify-core`` writes a six-gate summary into the same directory the full
    run writes twelve gates into. The documentation publishes twelve-gate facts,
    so comparing it against a core summary is a category error rather than a
    drift, and must skip explicitly instead of failing (REQ-JUDGE-003).
    """
    summary_path = vdc.REPORT_DIR / "verify_summary.json"
    try:
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    return summary.get("mode") != "core"


FULL_MODE_EVIDENCE = ARTIFACTS_READY and _full_mode_evidence()
CORE_MODE_REASON = (
    "verify_summary.json is from a --core run: the twelve-gate evidence set the "
    "documentation asserts is regenerated by `make verify`, whose authoritative "
    "documentation gate runs in judge/verify.py after every artifact exists"
)
NOT_READY_REASON = (
    "evidence artifacts not generated yet (run `make verify`); "
    "documentation-claim checks are explicit skips in this bootstrap position, "
    "and judge/verify.py re-runs the authoritative check after artifacts exist"
)


