"""Golden hashes for the frozen contract set (Phase 1 exit gate: "contracts frozen").

A digest alone proves "it changed"; it does not say *what* changed or whether the change was
intended. This tool keeps per-file hashes plus a payload digest, and distinguishes:

* ``--check``  — verify every recorded hash still matches (used by `make lint` and `make verify`);
* ``--write``  — refresh the golden file, which must happen **in the same commit** as an
  intentional contract change with a `docs/CR/` entry. A refresh without a CR is a review smell,
  not a build failure, so the tool prints the reminder instead of pretending to enforce it.

Usage:
    python -m tools.check_golden [--check|--write] [--json]
Exit codes: 0 all hashes match, 1 a hash drifted, 2 configuration error.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from tools.canonical_json import canonical_digest, sha256_hex

ROOT = Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "contracts"
GOLDEN = CONTRACTS / "GOLDEN.json"


def file_hashes() -> dict[str, dict[str, object]]:
    entries: dict[str, dict[str, object]] = {}
    for path in sorted(CONTRACTS.rglob("*.json")):
        if path.name == "GOLDEN.json":
            continue
        raw = path.read_bytes()
        entries[str(path.relative_to(CONTRACTS)).replace("\\", "/")] = {
            "sha256": hashlib.sha256(raw).hexdigest(),
            "bytes": len(raw),
        }
    return entries


def compute() -> dict:
    files = file_hashes()
    # Digest over the *byte hashes* rather than the parsed payload: canonical JSON deliberately
    # rejects floats, and fixture payloads contain JSON numbers such as `confidence`.
    contract_set_digest = canonical_digest({name: meta["sha256"] for name, meta in files.items()
                                            if not name.startswith("fixtures/")})
    fixtures_digest = canonical_digest({name: meta["sha256"] for name, meta in files.items()
                                        if name.startswith("fixtures/")})
    return {
        "golden_version": "1.0.0",
        "status": "provisional",
        "note": "Generated by `python -m tools.check_golden --write`. Refresh only together with a docs/CR/ entry.",
        "contract_set_digest": contract_set_digest,
        "fixtures_digest": fixtures_digest,
        "files": files,
    }


def run() -> dict:
    if not GOLDEN.is_file():
        return {"check": "golden", "status": "FAIL",
                "problems": ["contracts/GOLDEN.json is missing (run `python -m tools.check_golden --write`)"],
                "notes": []}
    recorded = json.loads(GOLDEN.read_text(encoding="utf-8"))
    current = compute()
    problems: list[str] = []
    for name, meta in recorded.get("files", {}).items():
        if name not in current["files"]:
            problems.append(f"{name}: recorded but missing from the contract set")
            continue
        if current["files"][name]["sha256"] != meta["sha256"]:
            problems.append(f"{name}: content changed since the freeze "
                            f"({meta['sha256'][:12]} -> {current['files'][name]['sha256'][:12]})")
    for name in sorted(set(current["files"]) - set(recorded.get("files", {}))):
        problems.append(f"{name}: new contract file not covered by the freeze")
    if recorded.get("contract_set_digest") != current["contract_set_digest"]:
        problems.append("contract_set_digest differs from the recorded freeze")
    if recorded.get("fixtures_digest") != current["fixtures_digest"]:
        problems.append("fixtures_digest differs from the recorded freeze")
    return {
        "check": "golden",
        "status": "PASS" if not problems else "FAIL",
        "files_checked": len(current["files"]),
        "contract_set_digest": current["contract_set_digest"],
        "problems": problems,
        "notes": ["refresh requires a docs/CR/ entry; the tool cannot verify intent"],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="refresh contracts/GOLDEN.json")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    if args.write:
        payload = compute()
        GOLDEN.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"golden: written {GOLDEN.relative_to(ROOT)} "
              f"({len(payload['files'])} files, set digest {payload['contract_set_digest'][:12]}…)")
        print("golden: remember to add a docs/CR/ entry describing the change")
        return 0
    try:
        result = run()
    except (json.JSONDecodeError, OSError) as exc:
        print(f"golden: CONFIG ERROR - {exc}")
        return 2
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print(f"golden: {result['status']}")
        for problem in result["problems"]:
            print(f"  - {problem}")
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
